"""Maintain the documentation navigation graph without executing indexed code."""
import argparse
from collections import defaultdict
import json
import os
from pathlib import Path
import re
from urllib.parse import quote,unquote,urlsplit

ROOT=Path(__file__).resolve().parents[1]
ROLES={
    'assignment':'Official assignment snapshot, dataset card and pinned provenance',
    'configs':'Source freeze manifests and explicit runtime preparation contracts',
    'deployments':'Source-only deployment preparations, bootstrap and owned-node operating instructions',
    'data':'Shared raw-data location; no duplicate training copy',
    'docs':'Operating guides, research, plans and reusable cases',
    'experiments':'Declared hypotheses and chronological results/failures',
    'reports':'Current handoff, interpretation, historical reports and measured evidence',
    'scripts':'CLI orchestration, preparation, profiling, recovery, checks and packaging',
    'src':'Reusable tokenizer/model/training/decoding/evaluation implementation',
    'kaggle':'Frozen remote kernel launch stages; do not edit their members',
    'notebooks':'Working inspection notebook',
    'submit':'Canonical inference notebook and later delivery requirements',
    'artifacts':'Ignored local bundles, bounded recovery/staging and live followers',
}
BINARY={'.pt','.zip','.bin','.parquet','.npy','.npz','.pyc'}


def inside(path):
    try:path.relative_to(ROOT);return True
    except ValueError:return False


def contents(folder):
    result=[]
    for path in sorted(folder.rglob('*')):
        rel=path.relative_to(folder)
        if any(part.startswith('.') or part=='__pycache__' for part in rel.parts):continue
        if not path.is_file() or path.is_symlink() or path.name=='INDEX.md':continue
        if folder.name=='artifacts' and path.suffix!='.md':continue
        if path.suffix in BINARY:continue
        result.append(path)
    return result


def link(label,target,from_dir):
    relative=os.path.relpath(target,from_dir)
    return f'[{label}](<{quote(relative,safe="/._-")}>)'


def group(folder,path):
    relative=path.relative_to(folder)
    if folder.name=='scripts':
        name=path.name
        for prefix,title in [('check_','Checks'),('tpu_check_','Checks'),('audit_','Audits'),
                             ('build_','Staging and notebook builders'),('package_','Packaging'),
                             ('profile_','Profiling'),('kaggle_','Kaggle operations'),
                             ('colab_','Colab operations')]:
            if name.startswith(prefix):return title
        return 'Other tools'
    if len(relative.parts)>1:return relative.parts[0].replace('_',' ').capitalize()
    return 'Folder documents and files'


def expected():
    folders=sorted(p for p in ROOT.iterdir() if p.is_dir() and not p.name.startswith('.'))
    unknown=[p.name for p in folders if p.name not in ROLES]
    if unknown:raise ValueError('Assign a documented purpose to new folders: '+', '.join(unknown))
    inventory=set();output={}
    root_files=sorted(p for p in ROOT.iterdir() if p.is_file() and not p.name.startswith('.'))
    root_index=ROOT/'PROJECT_INDEX.md'
    root_files=sorted(set(root_files)|{root_index})
    inventory.update(root_files)
    lines=['# Complete project index','','Generated by `scripts/docs_inventory.py`; edit folder roles in that tool.',
           'Navigation head: [START_HERE](START_HERE.md). Factual status lives in [HANDOFF](reports/HANDOFF.md).',
           'Hidden environments/VCS/caches and binary data/checkpoints are excluded. Artifact payloads are identified by retained manifests.','',
           '## Top-level documents and configuration','']
    lines += ['- '+link(p.name,p,ROOT) for p in root_files if p!=root_index]
    lines += ['','## Content folders','','| Folder | Purpose |','| --- | --- |']
    for folder in folders:
        index=folder/'INDEX.md';inventory.add(index)
        lines.append(f'| {link(folder.name,index,ROOT)} | {ROLES[folder.name]} |')
        files=contents(folder);inventory.update(files)
        parts=[f'# {folder.name.capitalize()} index','',ROLES[folder.name]+'.',
            '',link('Navigation head',ROOT/'START_HERE.md',folder)+' · '+link('Complete project index',root_index,folder),
            '', 'Generated by `scripts/docs_inventory.py`; refresh after adding/moving documents.','']
        groups=defaultdict(list)
        for path in files:groups[group(folder,path)].append(path)
        for title,entries in sorted(groups.items()):
            parts += [f'## {title}','']
            parts += ['- '+link(str(p.relative_to(folder)),p,folder) for p in entries]
            parts.append('')
        if folder.name=='artifacts':
            parts += ['## Recovery and staging roots','',
                'Directory links allow inspection; do not modify immutable stages/recoveries or download full optimizer/raw-array copies.','']
            roots=sorted(p for p in folder.iterdir() if p.is_dir() and not p.name.startswith('.'))
            for parent in roots:
                parts.append('- '+link(parent.name+'/',parent,folder))
                if parent.name=='kaggle':
                    parts += ['  - '+link(str(p.relative_to(folder))+'/',p,folder)
                              for p in sorted(parent.iterdir()) if p.is_dir() and not p.name.startswith('.')]
            parts.append('')
        output[index]='\n'.join(parts).rstrip()+'\n'
    output[root_index]='\n'.join(lines)+'\n'
    return output,inventory


def markdown_links(path):
    body=path.read_text()
    body=re.sub(r'```[\s\S]*?```','',body)
    for raw in re.findall(r'\[[^\]]*\]\(([^\n]*?)\)',body):
        raw=raw.strip()
        if raw.startswith('<'):
            end=raw.find('>');raw=raw[1:end]
        else:raw=raw.split(' "',1)[0].split(" '",1)[0]
        parsed=urlsplit(raw)
        if parsed.scheme or parsed.netloc or not parsed.path:continue
        target=unquote(parsed.path)
        target=re.sub(r':\d+$','',target)
        yield (path.parent/target).resolve(),parsed.fragment


def anchors(path):
    counts=defaultdict(int);result=set()
    for title in re.findall(r'^#{1,6}\s+(.+)$',path.read_text(),flags=re.M):
        slug=re.sub(r'[^\w -]','',title.strip().lower()).replace(' ','-')
        n=counts[slug];counts[slug]+=1
        result.add(slug if not n else f'{slug}-{n}')
    return result


def check(output,inventory):
    errors=[];graph={}
    for path,body in output.items():
        if not path.exists() or path.read_text()!=body:errors.append('stale/missing index: '+str(path.relative_to(ROOT)))
    for path in sorted(inventory):
        if path.suffix!='.md' or not path.exists():continue
        graph[path]=[]
        for target,fragment in markdown_links(path):
            if not inside(target):continue # external sibling references have separate evidence levels
            if not target.exists():errors.append(f'broken link: {path.relative_to(ROOT)} -> {target.relative_to(ROOT)}');continue
            if fragment and target.suffix=='.md' and unquote(fragment) not in anchors(target):
                errors.append(f'broken anchor: {path.relative_to(ROOT)} -> {target.relative_to(ROOT)}#{fragment}')
            graph[path].append(target)
    visited=set();queue=[ROOT/'START_HERE.md']
    while queue:
        path=queue.pop()
        if path in visited:continue
        visited.add(path);queue.extend(graph.get(path,[]))
    unreachable=sorted(p for p in inventory if p not in visited)
    errors += ['unreachable from START_HERE: '+str(p.relative_to(ROOT)) for p in unreachable]
    if errors:raise ValueError('\n'.join(errors))
    return {'navigation_head':'START_HERE.md','indexed_files':len(inventory),
            'markdown_documents':sum(p.suffix=='.md' for p in inventory),
            'folder_indexes':len(output)-1,'internal_links_and_reachability':'passed',
            'factual_claims_verified':False}


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--write',action='store_true');parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    if not (args.write or args.check):parser.error('choose --write and/or --check')
    output,inventory=expected()
    if args.write:
        for path,body in output.items():path.write_text(body)
        print(json.dumps({'generated_indexes':len(output)}))
    if args.check:print(json.dumps(check(output,inventory)))


if __name__=='__main__':main()
